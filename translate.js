async function generate() {
    const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY_1 });
    
    const prompt = `
    Translate the following Russian JSON dictionary into English, Spanish, and Arabic.
    Maintain the exact keys. Do not change the '{0}' variable.
    Return ONLY valid JSON with three root keys: "en", "es", "ar".
    Inside each, put the translated keys.
    
    JSON to translate:
    ${JSON.stringify(existing_ru, null, 2)}
    `;
    
    const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash',
        contents: prompt,
        config: {
            responseMimeType: "application/json"
        }
    });
    
    const res = JSON.parse(response.text);
    
    let content = fs.readFileSync('src/lib/i18n/translations.ts', 'utf-8');
    
    function insertIntoBlock(lang, newDict) {
        const marker = "  " + lang + ": {";
        const idx = content.indexOf(marker);
        if (idx === -1) return;
        const insertIdx = idx + marker.length + 1;
        
        let lines = [];
        for (const [k, v] of Object.entries(newDict)) {
            const vEsc = v.replace(/'/g, "\\'");
            lines.push("    '" + k + "': '" + vEsc + "',");
        }
        
        const insertStr = lines.join('\n') + '\n';
        content = content.slice(0, insertIdx) + insertStr + content.slice(insertIdx);
    }
    
    insertIntoBlock('ru', existing_ru);
    insertIntoBlock('en', res['en']);
    insertIntoBlock('es', res['es']);
    insertIntoBlock('ar', res['ar']);
    
    fs.writeFileSync('src/lib/i18n/translations.ts', content, 'utf-8');
    console.log("translations.ts updated successfully!");
}

generate().catch(console.error);
